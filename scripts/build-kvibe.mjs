// Build kvibe/src/index.js: the K-Vibe worker with the shared avatar page inlined (one file, no imports).
// Usage: node scripts/build-kvibe.mjs
import fs from 'node:fs';
const page = fs.readFileSync(new URL('../src/avatar-page.js', import.meta.url), 'utf8').replace(/^export /gm, '');
const worker = fs.readFileSync(new URL('../src/kvibe-worker.js', import.meta.url), 'utf8')
  .replace(/^import \{[^}]*\} from '\.\/avatar-page\.js';\n/m, '');
const out = `// GENERATED by scripts/build-kvibe.mjs from src/avatar-page.js + src/kvibe-worker.js. Do not edit.\n\n${page}\n${worker}`;
fs.mkdirSync(new URL('../kvibe/src/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../kvibe/src/index.js', import.meta.url), out);
console.log(`kvibe/src/index.js: ${out.length} bytes`);
